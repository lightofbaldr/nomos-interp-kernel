  await page.evaluate(()=>scrollTo(0,0));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'evidence/mobile-matched.png',fullPage:true});
  await page.getByRole('tab',{name:'Free generation',exact:true}).click();
  await ready('S1/joy_0.7.free.json');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'Source & gates'}).click();
