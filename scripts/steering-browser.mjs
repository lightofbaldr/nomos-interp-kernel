  const layer=p.workspace.find(l=>l.layer===48);
  for(const side of ['baseline','steered']) {
    const expected=layer.candidates.filter(c=>c[`${side}_rank`]!==null && c[`${side}_rank`]<=8).sort((a,b)=>a[`${side}_rank`]-b[`${side}_rank`]);
    const rows=page.locator(`.candidate-panel.${side} .candidate-row`);
    assert.equal(await rows.count(),expected.length);
    for(let i=0;i<expected.length;i++) {await has(rows.nth(i),`#${expected[i].id}`);await has(rows.nth(i),expected[i][side].toFixed(2));}
  }
  assert.equal(await page.locator('.candidate-panel.difference .difference-row').count(),layer.candidates.length);
  await has(page.locator('.bound-label'),'Bounds');
  await has(page.locator('.difference-list'),'≥'); await has(page.locator('.difference-list'),'≤');
  await page.locator('.candidate-panel.steered .candidate-row').first().click();
  assert.ok(await page.locator('.candidate-detail').isVisible());
  assert.ok(await page.locator('.candidate-row.selected,.difference-row.selected').count()>=2);
  await page.getByRole('searchbox',{name:'Filter displayed candidates'}).fill('not-a-token-in-this-union');
  await page.getByRole('heading',{name:'No matching displayed candidates'}).waitFor();
  await page.getByRole('searchbox',{name:'Filter displayed candidates'}).fill('');
  await page.getByRole('button',{name:'L36',exact:true}).click();
  await has(page.locator('.workspace-toolbar'),'L36');
  await page.getByRole('button',{name:'Prompt start',exact:true}).click();
  await has(page.getByTestId('workspace-missing'),'unavailable');
  assert.equal(await page.locator('.candidate-row').count(),0);
  await page.getByRole('slider',{name:'Consumed position'}).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('spinbutton',{name:'Position',exact:true}).inputValue(),'1');
  await page.getByRole('button',{name:'Recorded end',exact:true}).click();
  assert.equal(Number(await page.getByRole('spinbutton',{name:'Position',exact:true}).inputValue()),raw.comparison.positions.at(-1).pos);
  await page.getByRole('button',{name:'Show all 39 directions'}).click();
  assert.equal(await page.locator('.heatmap tbody tr').count(),39);
  await page.getByRole('button',{name:'Show focus directions'}).click();
  await page.getByRole('button',{name:'Source & gates'}).click();
  await page.getByRole('dialog').waitFor();
  await has(page.getByRole('dialog'),'library_sha256');await has(page.getByRole('dialog'),'G7_delivered');
  await page.waitForFunction(()=>document.activeElement?.closest('[role="dialog"]') !== null);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'detached'});
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.waitForFunction(()=>document.activeElement?.textContent?.includes('Source & gates'));
  assert.equal(await page.getByRole('button',{name:'Source & gates'}).evaluate(e=>e===document.activeElement),true);
  // Baseline/zero controls remain real records, never manufactured from the live UI state.
  await page.getByRole('combobox',{name:'Intervention',exact:true}).selectOption('zero');
  await ready('S1/zero.matched.json');
  for (const score of await page.locator('.difference-row .score').allTextContents()) assert.equal(score,'0.00');
  await page.getByRole('combobox',{name:'Intervention',exact:true}).selectOption('base_repeat');
  await page.getByRole('heading',{name:'No matched-input replay for this arm'}).waitFor();
  assert.equal(await page.locator('.candidate-row').count(),0);
  await page.getByRole('tab',{name:'Free generation',exact:true}).click();
  await ready('S1/base_repeat.free.json');
  assert.equal(await page.getByTestId('divergence').count(),0);
  await page.getByRole('combobox',{name:'Intervention',exact:true}).selectOption('joy_0.7');
  await ready('S1/joy_0.7.free.json');
  await has(page.getByTestId('divergence'),'58');
  assert.equal(await page.getByRole('slider',{name:'Consumed position'}).getAttribute('max'),'57');
  assert.equal(await page.locator('.response-card .response-text').count(),2);
  await has(page.locator('.response-card.steered .response-text'),'HUGE win');
  await page.getByRole('link',{name:'Read own continuations'}).click();
  const modeBox=await page.getByRole('tab',{name:'Free generation',exact:true}).boundingBox();
  assert.ok(modeBox && modeBox.y>=0 && modeBox.y<100, 'mode remains visible at the responses');
  await page.locator('.response-card.baseline .track summary').click();
  await page.locator('.response-card.steered .track summary').click();
  assert.equal(await page.locator('.track-tokens span').count(),506);
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'evidence/desktop-free.png',fullPage:true});
  // Every scenario loads from the second data root, with no stale prior comparison.
  for(const name of ['T1','T2','T3','T4']) {
    await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption(`dataset-2:${name}`);
    await ready(`${name}/joy_0.7.free.json`);
    await has(page.locator('.prompt-copy'),name);
  }
  await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('dataset-1:S1');
  await ready('S1/joy_0.7.free.json');
  await page.getByRole('tab',{name:'Matched input replay',exact:true}).click();
