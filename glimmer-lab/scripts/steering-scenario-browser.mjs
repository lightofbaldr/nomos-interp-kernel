import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {harness} from './harness.mjs';
import {DEFAULT_STEERING_DATA} from '../src/lib/server/steering-data.ts';
import {scenarioFixture} from '../tests/steering/scenario-fixture.ts';
const DATA=process.env.GLIMMER_STEERDIFF_DATA_DIR ?? DEFAULT_STEERING_DATA;
const h=await harness(false,{GLIMMER_STEERDIFF_DATA_DIR:DATA}),origin=h.base,browser=h.browser;
try {
  const {index,makeBundle}=scenarioFixture(),files={'index.json':JSON.stringify(index)},hashes={};
  for(const ref of index.comparisons)files[ref.path]=JSON.stringify(makeBundle(ref));
  for(const [p,s] of Object.entries(files))hashes[p]=createHash('sha256').update(s).digest('hex');
  const catalog={schema:'glimmer.local-catalog/1',datasets:[{id:'fixture',run:index.run,index:'fixture/index.json',hashes}]};
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/data/**',route=>{const pathname=new URL(route.request().url()).pathname; const body=pathname==='/data/catalog.json'?JSON.stringify(catalog):files[pathname.replace('/data/fixture/','')];return route.fulfill({status:body?200:404,contentType:'application/json',body:body??'not found'});});
  await page.goto(origin+'/steering-diff');
  await page.getByRole('heading',{name:'Choose an intervention',exact:true}).waitFor();
  assert.equal(await page.getByRole('combobox',{name:'Intervention',exact:true}).inputValue(),'');
  await page.getByRole('combobox',{name:'Intervention',exact:true}).selectOption('joy_minus');
  const ready=async s=>page.waitForFunction(v=>document.querySelector('.page-footer')?.textContent.includes(v),s);
  await ready('TEST-RECORDED/joy_minus.matched.json');
  assert.equal(await page.getByRole('combobox',{name:'Intervention',exact:true}).evaluate(e=>e.selectedOptions[0].textContent),'Joy · -0.5 · counter-steered');
  assert.ok((await page.locator('.signed-note').textContent()).includes('not a separately learned opposite emotion'));
  const provenance=page.getByRole('region',{name:'Recorded episode provenance'});
  assert.ok((await provenance.textContent()).includes('Historical label lie'));
  assert.ok((await provenance.textContent()).includes('Classifier overclaim'));
  await page.getByRole('button',{name:/Thinking tail · 1953/}).click();
  assert.equal(await page.getByRole('spinbutton',{name:'Position',exact:true}).inputValue(),'1953');
  await page.getByRole('button',{name:/Answer start · 2209/}).click();
  assert.equal(await page.getByRole('spinbutton',{name:'Position',exact:true}).inputValue(),'2209');
  await page.getByRole('button',{name:'Prefill start',exact:true}).click();
  assert.ok(await page.getByTestId('workspace-missing').isVisible());
  await page.getByRole('button',{name:'Source identity & recorded boundaries'}).click();
  await page.locator('.scenario-boundaries').waitFor();
  assert.ok((await page.locator('.scenario-boundaries').textContent()).includes('1953'));
  assert.ok((await page.locator('.scenario-context .identity-json').textContent()).includes('a'.repeat(64)));
  await page.getByRole('button',{name:'Source identity & recorded boundaries'}).click();
  await page.getByRole('button',{name:/Thinking tail · 1953/}).click();
  assert.ok((await page.locator('.response-section .section-description').textContent()).includes('separate answer scenario'));
  await fs.mkdir('evidence',{recursive:true});
  await page.screenshot({path:'evidence/scenario-fixture-replay.png',fullPage:true});
  // Normal scenario selection retains the active mode; only the explicit paired-view action changes it.
  await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('fixture:TEST-CONTINUATION');
  await page.getByRole('heading',{name:'No matched-input replay for this arm'}).waitFor();
  assert.equal(await page.getByRole('tab',{name:'Matched input replay',exact:true}).getAttribute('aria-selected'),'true');
  assert.ok((await page.locator('.mode-explanation:visible').textContent()).includes('not exported'));
  await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('fixture:TEST-RECORDED');
  await ready('TEST-RECORDED/joy_minus.matched.json');
  await page.getByRole('button',{name:'Open TEST-CONTINUATION · free answer',exact:false}).click();
  await ready('TEST-CONTINUATION/joy_minus.free.json');
  assert.equal(await page.getByRole('tab',{name:'Free generation',exact:true}).getAttribute('aria-selected'),'true');
  assert.ok((await page.locator('.mode-explanation:visible').textContent()).includes('recorded thinking is prefilled'));
  assert.equal(await page.getByRole('button',{name:/Reasoning start · unavailable/}).isDisabled(),true);
  await page.getByRole('button',{name:/Answer start · 2211/}).click();
  assert.equal(await page.getByRole('spinbutton',{name:'Position',exact:true}).inputValue(),'2211');
  assert.equal(await page.getByRole('slider',{name:'Consumed position'}).getAttribute('max'),'2211');
  assert.ok((await page.locator('.response-section .section-description').textContent()).includes('historical source label does not classify these answers'));
  await page.getByRole('combobox',{name:'Intervention',exact:true}).selectOption('sad_minus');
  await ready('TEST-CONTINUATION/sad_minus.free.json');
  assert.ok((await page.getByRole('combobox',{name:'Intervention',exact:true}).evaluate(e=>e.selectedOptions[0].textContent)).includes('Sadness [sad] · -0.5'));
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'evidence/scenario-fixture-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await fs.writeFile('evidence/scenario-browser-results.json',JSON.stringify({pass:true,synthetic:true,prefill:1953,stepped:1004,checks:['explicit initial arm selection','signed labels','historical provenance','thinking-tail jump','answer jump','null prefill workspace','source identity','mode retained on selection','explicit paired action','free prefix wording','unavailable channel','no jump past divergence','mobile overflow'],errors},null,2));
  console.log('SCENARIO BROWSER PASS: synthetic 1,953-token prefix + 1,004 stepped rows; 13 checks. This is a fixture check, not real-bundle validation.');
} finally { await h.close(); }
